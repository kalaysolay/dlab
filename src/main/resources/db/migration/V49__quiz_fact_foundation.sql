-- Факты не маскируются под предметные SCQ: отдельный банк и версии с boolean ключом.
create table fact_sets (
    id bigint generated by default as identity primary key,
    code varchar(96) not null unique,
    status varchar(32) not null default 'DRAFT' check (status in ('DRAFT', 'NEEDS_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED')),
    title_ru varchar(255) not null,
    title_kk varchar(255) not null,
    source_policy text not null,
    created_by bigint references app_users(id) on delete set null,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now()
);
create table fact_statements (
    id bigint generated by default as identity primary key,
    set_id bigint not null references fact_sets(id) on delete restrict,
    status varchar(32) not null default 'DRAFT' check (status in ('DRAFT', 'NEEDS_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED')),
    published_version_id bigint,
    draft_version_id bigint,
    created_by bigint references app_users(id) on delete set null,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint ck_fact_statement_pointers check (published_version_id is null or draft_version_id is null or published_version_id <> draft_version_id)
);
create table fact_statement_versions (
    id bigint generated by default as identity primary key,
    statement_id bigint not null references fact_statements(id) on delete restrict,
    version_no integer not null check (version_no > 0),
    status varchar(32) not null default 'DRAFT' check (status in ('DRAFT', 'NEEDS_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED')),
    text_ru text not null,
    text_kk text not null,
    truth_value boolean not null,
    explanation_ru text not null,
    explanation_kk text not null,
    source_reference text not null,
    universal_audience boolean not null default false,
    published_at timestamp with time zone,
    created_by bigint references app_users(id) on delete set null,
    reviewed_by bigint references app_users(id) on delete set null,
    reviewed_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint uq_fact_version_no unique (statement_id, version_no),
    constraint uq_fact_version_owner unique (statement_id, id)
);
alter table fact_statements add constraint fk_fact_statement_published
    foreign key (id, published_version_id) references fact_statement_versions(statement_id, id) on delete restrict;
alter table fact_statements add constraint fk_fact_statement_draft
    foreign key (id, draft_version_id) references fact_statement_versions(statement_id, id) on delete restrict;
create table fact_statement_grades (
    statement_version_id bigint not null references fact_statement_versions(id) on delete restrict,
    grade_id bigint not null references grades(id) on delete restrict,
    primary key (statement_version_id, grade_id)
);
create table quiz_fact_game_configs (
    game_version_id bigint primary key,
    game_type varchar(32) not null default 'TRUE_FALSE' check (game_type = 'TRUE_FALSE'),
    fact_set_id bigint not null references fact_sets(id) on delete restrict,
    constraint fk_quiz_fact_game_type foreign key (game_version_id, game_type)
        references quiz_game_versions(id, game_type) on delete restrict
);

create index idx_fact_sets_status on fact_sets(status);
create index idx_fact_statements_set_status on fact_statements(set_id, status);
create index idx_fact_versions_status_audience on fact_statement_versions(status, universal_audience);
create index idx_fact_grades_lookup on fact_statement_grades(grade_id, statement_version_id);
