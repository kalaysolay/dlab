-- Первый добавочный блок foundation: игры, версии, предметная конфигурация и классы.
-- Старые quiz_rooms/rounds/answers не меняются. Словарные/фактовые configs с настоящими
-- FK добавляются только вместе с соответствующими банками, не с фиктивными источниками.
create table quiz_games (
    id bigint generated by default as identity primary key,
    code varchar(96) not null unique,
    status varchar(32) not null default 'DRAFT',
    catalog_visible boolean not null default true,
    published_version_id bigint,
    draft_version_id bigint,
    created_by bigint references app_users(id) on delete set null,
    visibility_updated_by bigint references app_users(id) on delete set null,
    visibility_updated_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint ck_quiz_games_status check (status in ('DRAFT', 'NEEDS_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED')),
    constraint ck_quiz_games_distinct_versions check (
        published_version_id is null or draft_version_id is null or published_version_id <> draft_version_id
    )
);

create table quiz_game_versions (
    id bigint generated by default as identity primary key,
    game_id bigint not null references quiz_games(id) on delete restrict,
    version_no integer not null,
    game_type varchar(32) not null,
    status varchar(32) not null default 'DRAFT',
    title_ru varchar(255) not null,
    title_kk varchar(255) not null,
    description_ru text,
    description_kk text,
    mechanic_label_ru varchar(128),
    mechanic_label_kk varchar(128),
    card_style varchar(32) not null default 'default',
    catalog_order integer not null default 0,
    grade_selection_mode varchar(32) not null default 'NONE',
    audience_policy varchar(32) not null default 'UNIVERSAL',
    default_question_count integer not null default 10,
    min_question_count integer not null default 1,
    max_question_count integer not null default 20,
    default_round_seconds integer not null default 20,
    min_round_seconds integer not null default 5,
    max_round_seconds integer not null default 120,
    question_count_editable boolean not null default false,
    round_seconds_editable boolean not null default false,
    max_players integer not null default 4,
    published_at timestamp with time zone,
    created_by bigint references app_users(id) on delete set null,
    reviewed_by bigint references app_users(id) on delete set null,
    reviewed_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint uq_quiz_game_version_no unique (game_id, version_no),
    constraint uq_quiz_game_version_owner unique (game_id, id),
    constraint uq_quiz_game_version_type_ref unique (id, game_type),
    constraint ck_quiz_game_version_no check (version_no > 0),
    constraint ck_quiz_game_version_type check (game_type in ('WORD_TRANSLATION', 'SUBJECT_QUIZ', 'TRUE_FALSE')),
    constraint ck_quiz_game_version_status check (status in ('DRAFT', 'NEEDS_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED')),
    constraint ck_quiz_game_grade_mode check (grade_selection_mode in ('NONE', 'PROFILE_DEFAULT', 'REQUIRED')),
    constraint ck_quiz_game_audience check (audience_policy in ('UNIVERSAL', 'PARTICIPANT_GRADES', 'ROOM_GRADE', 'FIXED_GRADES')),
    constraint ck_quiz_game_grade_policy check (
        (audience_policy <> 'ROOM_GRADE' or grade_selection_mode in ('PROFILE_DEFAULT', 'REQUIRED'))
        and (audience_policy <> 'PARTICIPANT_GRADES' or grade_selection_mode = 'NONE')
    ),
    constraint ck_quiz_game_question_count check (
        min_question_count > 0 and min_question_count <= default_question_count and default_question_count <= max_question_count
    ),
    constraint ck_quiz_game_round_seconds check (
        min_round_seconds > 0 and min_round_seconds <= default_round_seconds and default_round_seconds <= max_round_seconds
    ),
    constraint ck_quiz_game_max_players check (max_players between 1 and 4)
);

-- Составные FK не дают указателю одной игры ссылаться на версию другой игры.
alter table quiz_games add constraint fk_quiz_game_published_version
    foreign key (id, published_version_id) references quiz_game_versions(game_id, id) on delete restrict;
alter table quiz_games add constraint fk_quiz_game_draft_version
    foreign key (id, draft_version_id) references quiz_game_versions(game_id, id) on delete restrict;

create table quiz_subject_game_configs (
    game_version_id bigint primary key,
    game_type varchar(32) not null default 'SUBJECT_QUIZ',
    subject_id bigint not null references subjects(id) on delete restrict,
    difficulty integer,
    constraint ck_quiz_subject_game_difficulty check (difficulty is null or difficulty between 1 and 5),
    constraint ck_quiz_subject_game_type check (game_type = 'SUBJECT_QUIZ'),
    constraint fk_quiz_subject_game_type foreign key (game_version_id, game_type)
        references quiz_game_versions(id, game_type) on delete restrict
);

create table quiz_subject_game_question_types (
    game_version_id bigint not null references quiz_subject_game_configs(game_version_id) on delete restrict,
    question_type varchar(32) not null,
    primary key (game_version_id, question_type),
    constraint ck_quiz_subject_game_question_type check (question_type in ('SCQ', 'MCQ', 'MATCHING', 'FILL_IN'))
);

create table quiz_game_version_grades (
    game_version_id bigint not null references quiz_game_versions(id) on delete restrict,
    grade_id bigint not null references grades(id) on delete restrict,
    primary key (game_version_id, grade_id)
);

create index idx_quiz_games_catalog on quiz_games(status, catalog_visible);
create index idx_quiz_game_versions_type_order on quiz_game_versions(game_type, catalog_order);
create index idx_quiz_game_grades_lookup on quiz_game_version_grades(grade_id, game_version_id);
