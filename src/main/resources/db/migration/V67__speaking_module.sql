-- Разговорник владеет своей историей и наблюдениями, не меняя школьную аналитику.
create table speaking_sessions (
    id uuid primary key,
    student_profile_id bigint not null references student_profiles(id),
    create_request_id uuid not null,
    scenario_code varchar(64) not null,
    scenario_snapshot text not null,
    level varchar(2) not null,
    explanation_language varchar(2) not null,
    provider_version varchar(64) not null,
    status varchar(24) not null,
    active_slot integer,
    accepted_turns integer not null default 0,
    assisted_next boolean not null default false,
    revision bigint not null default 0,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    unique(student_profile_id, create_request_id),
    unique(student_profile_id, active_slot),
    unique(id, student_profile_id),
    check (level in ('A2','B1','B2')),
    check (explanation_language in ('ru','kk')),
    check (accepted_turns between 0 and 12),
    check ((status = 'ACTIVE' and active_slot = 1) or (status <> 'ACTIVE' and active_slot is null))
);
create index speaking_sessions_owner_date on speaking_sessions(student_profile_id, created_at);

create table speaking_turns (
    id uuid primary key,
    session_id uuid not null references speaking_sessions(id) on delete cascade,
    request_id uuid not null,
    sequence_no integer not null,
    source varchar(16) not null,
    learner_text varchar(2000) not null,
    reaction_text varchar(240) not null,
    question_text varchar(500) not null,
    created_at timestamp with time zone not null,
    unique(session_id, request_id),
    unique(session_id, sequence_no),
    unique(id, session_id)
);

create table speaking_observations (
    id uuid primary key,
    student_profile_id bigint not null,
    session_id uuid not null,
    turn_id uuid not null,
    skill_code varchar(64) not null,
    kind varchar(16) not null,
    original varchar(200) not null,
    corrected varchar(200) not null,
    explanation varchar(300) not null,
    evidence varchar(16) not null,
    source varchar(16) not null,
    assisted boolean not null default false,
    created_at timestamp with time zone not null,
    expires_at timestamp with time zone not null,
    foreign key(session_id, student_profile_id) references speaking_sessions(id, student_profile_id) on delete cascade,
    foreign key(turn_id, session_id) references speaking_turns(id, session_id) on delete cascade,
    unique(turn_id, skill_code, original, corrected),
    check(kind in ('error','style')),
    check(evidence in ('suggested','confirmed','disputed'))
);
create index speaking_observations_owner_skill on speaking_observations(student_profile_id, skill_code, created_at);

-- Счётчик не содержит ученического текста и не сбрасывается удалением истории.
create table speaking_daily_usage (
    id bigint generated by default as identity primary key,
    student_profile_id bigint not null references student_profiles(id),
    usage_day date not null,
    sessions_started integer not null,
    unique(student_profile_id, usage_day)
);
