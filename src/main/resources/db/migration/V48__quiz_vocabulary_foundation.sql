-- Словарный банк: стабильное учебное значение отдельно от проверяемых редакций.
-- Опубликованные указатели принадлежат своему владельцу; удаление истории не каскадное.
create table vocabulary_sets (
    id bigint generated by default as identity primary key,
    code varchar(96) not null unique,
    source_language varchar(8) not null,
    target_language varchar(8) not null,
    status varchar(32) not null default 'DRAFT',
    published_version_id bigint,
    draft_version_id bigint,
    created_by bigint references app_users(id) on delete set null,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint uq_vocabulary_set_pair unique (id, source_language, target_language),
    constraint ck_vocabulary_set_direction check (
        (source_language in ('en', 'kk') and target_language = 'ru')
        or (source_language = 'ru' and target_language = 'kk')
    ),
    constraint ck_vocabulary_set_status check (status in ('DRAFT', 'NEEDS_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED')),
    constraint ck_vocabulary_set_pointers check (published_version_id is null or draft_version_id is null or published_version_id <> draft_version_id)
);

create table vocabulary_set_versions (
    id bigint generated by default as identity primary key,
    set_id bigint not null references vocabulary_sets(id) on delete restrict,
    version_no integer not null check (version_no > 0),
    status varchar(32) not null default 'DRAFT' check (status in ('DRAFT', 'NEEDS_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED')),
    title_ru varchar(255) not null,
    title_kk varchar(255) not null,
    source_reference text not null,
    cross_set_distractors_allowed boolean not null default false,
    published_at timestamp with time zone,
    created_by bigint references app_users(id) on delete set null,
    reviewed_by bigint references app_users(id) on delete set null,
    reviewed_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint uq_vocabulary_set_version_no unique (set_id, version_no),
    constraint uq_vocabulary_set_version_owner unique (set_id, id)
);
alter table vocabulary_sets add constraint fk_vocabulary_set_published
    foreign key (id, published_version_id) references vocabulary_set_versions(set_id, id) on delete restrict;
alter table vocabulary_sets add constraint fk_vocabulary_set_draft
    foreign key (id, draft_version_id) references vocabulary_set_versions(set_id, id) on delete restrict;

create table vocabulary_items (
    id bigint generated by default as identity primary key,
    set_id bigint not null references vocabulary_sets(id) on delete restrict,
    status varchar(32) not null default 'DRAFT' check (status in ('DRAFT', 'NEEDS_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED')),
    published_version_id bigint,
    draft_version_id bigint,
    created_by bigint references app_users(id) on delete set null,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint ck_vocabulary_item_pointers check (published_version_id is null or draft_version_id is null or published_version_id <> draft_version_id)
);
create table vocabulary_item_versions (
    id bigint generated by default as identity primary key,
    item_id bigint not null references vocabulary_items(id) on delete restrict,
    version_no integer not null check (version_no > 0),
    status varchar(32) not null default 'DRAFT' check (status in ('DRAFT', 'NEEDS_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED')),
    source_text varchar(512) not null,
    source_normalized varchar(512) not null,
    pronunciation varchar(255),
    part_of_speech varchar(64),
    meaning_note_ru text,
    meaning_note_kk text,
    difficulty integer not null default 1 check (difficulty between 1 and 5),
    source_reference text not null,
    universal_audience boolean not null default false,
    published_at timestamp with time zone,
    created_by bigint references app_users(id) on delete set null,
    reviewed_by bigint references app_users(id) on delete set null,
    reviewed_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint uq_vocabulary_item_version_no unique (item_id, version_no),
    constraint uq_vocabulary_item_version_owner unique (item_id, id)
);
alter table vocabulary_items add constraint fk_vocabulary_item_published
    foreign key (id, published_version_id) references vocabulary_item_versions(item_id, id) on delete restrict;
alter table vocabulary_items add constraint fk_vocabulary_item_draft
    foreign key (id, draft_version_id) references vocabulary_item_versions(item_id, id) on delete restrict;

create table vocabulary_item_answers (
    id bigint generated by default as identity primary key,
    item_version_id bigint not null references vocabulary_item_versions(id) on delete restrict,
    answer_text varchar(512) not null,
    answer_normalized varchar(512) not null,
    is_primary boolean not null,
    primary_marker integer,
    -- Явный IS NOT NULL не позволяет SQL UNKNOWN обойти CHECK для primary.
    constraint ck_vocabulary_primary_marker check (
        (is_primary = true and primary_marker is not null and primary_marker = 1)
        or (is_primary = false and primary_marker is null)
    ),
    constraint uq_vocabulary_answer_text unique (item_version_id, answer_normalized),
    constraint uq_vocabulary_answer_primary unique (item_version_id, primary_marker)
);
create table vocabulary_item_grades (
    item_version_id bigint not null references vocabulary_item_versions(id) on delete restrict,
    grade_id bigint not null references grades(id) on delete restrict,
    primary key (item_version_id, grade_id)
);
create table vocabulary_distractor_exclusions (
    id bigint generated by default as identity primary key,
    item_version_id bigint not null references vocabulary_item_versions(id) on delete restrict,
    excluded_item_version_id bigint not null references vocabulary_item_versions(id) on delete restrict,
    reason text not null,
    created_by bigint references app_users(id) on delete set null,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint ck_vocabulary_exclusion_self check (item_version_id <> excluded_item_version_id),
    constraint uq_vocabulary_exclusion unique (item_version_id, excluded_item_version_id)
);

create table quiz_word_game_configs (
    game_version_id bigint primary key,
    game_type varchar(32) not null default 'WORD_TRANSLATION' check (game_type = 'WORD_TRANSLATION'),
    vocabulary_set_id bigint not null,
    source_language varchar(8) not null,
    target_language varchar(8) not null,
    constraint fk_quiz_word_game_type foreign key (game_version_id, game_type)
        references quiz_game_versions(id, game_type) on delete restrict,
    constraint fk_quiz_word_game_pair foreign key (vocabulary_set_id, source_language, target_language)
        references vocabulary_sets(id, source_language, target_language) on delete restrict
);

create index idx_vocabulary_sets_status_pair on vocabulary_sets(status, source_language, target_language);
create index idx_vocabulary_items_set_status on vocabulary_items(set_id, status);
create index idx_vocabulary_versions_normalized on vocabulary_item_versions(source_normalized);
create index idx_vocabulary_versions_status_audience on vocabulary_item_versions(status, universal_audience);
create index idx_vocabulary_grades_lookup on vocabulary_item_grades(grade_id, item_version_id);
create index idx_vocabulary_exclusions_reverse on vocabulary_distractor_exclusions(excluded_item_version_id);
