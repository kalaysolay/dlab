-- Накапливаем обращения к переводчику без публичного API и интерфейса истории.
create table translation_request_history (
    id bigint generated by default as identity primary key,
    user_id bigint references app_users(id) on delete set null,
    actor_email varchar(320) not null,
    operation varchar(16) not null check (operation in ('TRANSLATE', 'EXPLAIN')),
    direction varchar(32) not null check (direction in ('KAZAKH_TO_RUSSIAN', 'RUSSIAN_TO_KAZAKH')),
    source_text text not null,
    translated_text text,
    explanation_text text,
    explanation_language varchar(16),
    explanation_mode varchar(16),
    status varchar(16) not null check (status in ('PENDING', 'SUCCESS', 'FAILED')),
    provider varchar(32),
    model text,
    error_code text,
    created_at timestamp with time zone not null,
    completed_at timestamp with time zone
);

create index idx_translation_history_user_time on translation_request_history(user_id, created_at);
create index idx_translation_history_created_at on translation_request_history(created_at);
