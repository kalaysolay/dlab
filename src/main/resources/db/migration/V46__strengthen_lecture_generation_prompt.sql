Перед отправкой молча проверь: обе версии присутствуют; тема явно названа; разделов не меньше 3; абзацев не меньше 8; объём каждой версии не меньше 900 символов; факты и вычисления согласованы; paragraphs не содержат разметку; каждая формула валидна. Верни только завершённый JSON.',
    'migration',
    CURRENT_TIMESTAMP
FROM ai_prompts p
LEFT JOIN ai_prompt_versions v ON v.prompt_code = p.code
WHERE p.code = 'LECTURE_GENERATE'
GROUP BY p.code;

UPDATE ai_prompts
SET active_version = (
        SELECT MAX(v.version_no)
        FROM ai_prompt_versions v
        WHERE v.prompt_code = 'LECTURE_GENERATE'
    ),
    updated_by = 'migration',
    updated_at = CURRENT_TIMESTAMP
WHERE code = 'LECTURE_GENERATE';
