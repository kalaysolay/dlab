-- История редакционных переходов банков. Полиморфная ссылка хранит тип объекта и его ID:
-- версии банков уже защищены собственными FK, а единый журнал нужен для аудита workflow.
create table quiz_content_editorial_events (
    id bigint generated by default as identity primary key,
    content_type varchar(48) not null,
    content_id bigint not null,
    version_id bigint,
    from_status varchar(32) not null,
    to_status varchar(32) not null,
    actor_id bigint references app_users(id) on delete set null,
    created_at timestamp with time zone not null default now(),
    constraint ck_quiz_content_event_type check (content_type in ('VOCABULARY_SET', 'VOCABULARY_ITEM', 'FACT_SET', 'FACT_STATEMENT')),
    constraint ck_quiz_content_event_from check (from_status in ('DRAFT', 'NEEDS_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED')),
    constraint ck_quiz_content_event_to check (to_status in ('DRAFT', 'NEEDS_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED'))
);

create index idx_quiz_content_events_target
    on quiz_content_editorial_events(content_type, content_id, created_at);
