-- Подключение и недельная подписка общие для всех детей родителя.
create table parent_telegram_subscriptions (
    parent_id bigint primary key references parent_profiles(id) on delete cascade,
    telegram_user_id bigint unique,
    chat_id bigint unique,
    connected boolean not null default false,
    enabled boolean not null default false,
    language varchar(2) not null default 'ru',
    send_day integer not null default 1 check (send_day between 1 and 7),
    send_time time not null default '09:00:00',
    zone_id varchar(64) not null default 'Asia/Almaty',
    next_run_at timestamp with time zone,
    generation integer not null default 0
);
create table parent_telegram_tokens (
    token_hash varchar(64) primary key,
    parent_id bigint not null references parent_telegram_subscriptions(parent_id) on delete cascade,
    expires_at timestamp with time zone not null
);
create table parent_report_deliveries (
    id bigint generated by default as identity primary key,
    parent_id bigint not null references parent_telegram_subscriptions(parent_id) on delete cascade,
    student_id bigint not null references student_profiles(id) on delete cascade,
    link_id bigint not null references parent_student_links(id) on delete cascade,
    week_start date not null,
    generation integer not null,
    full_text text not null,
    message_text text not null,
    status varchar(24) not null default 'PENDING',
    attempts integer not null default 0,
    next_attempt_at timestamp with time zone not null,
    message_id bigint,
    error_code varchar(64),
    unique(parent_id, student_id, week_start)
);
create index idx_parent_reports_due on parent_report_deliveries(status, next_attempt_at);
create table parent_telegram_updates (
    update_id bigint primary key,
    processed_at timestamp with time zone not null
);
